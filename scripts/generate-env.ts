import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

function generateEnv() {
  const envPath = path.resolve(__dirname, '../.env');

  if (fs.existsSync(envPath)) {
    console.log('ℹ️  .env file already exists. Skipping generation to prevent overwriting existing configuration.');
    return;
  }

  const generateSecret = (bytes = 32): string => {
    return crypto.randomBytes(bytes).toString('hex');
  };

  const postgresPassword = generateSecret(16);
  const notificationDbPassword = generateSecret(16);
  const queueDbPassword = generateSecret(16);
  const internalToken = generateSecret(32);
  const jwtAccessSecret = generateSecret(32);
  const jwtRefreshSecret = generateSecret(32);
  const grafanaAdminPassword = generateSecret(16);

  const envContent = `# ==============================================================================
# QueueLess Environment Configuration
# Automatically generated by npm run gen:env
# ==============================================================================

# Core Application Configuration
NODE_ENV=production
PORT=5000
API_PREFIX=/api
FRONTEND_ORIGIN=http://localhost:8080
TRUST_PROXY=1

# PostgreSQL Database Configuration
POSTGRES_USER=postgres
POSTGRES_PASSWORD=${postgresPassword}
POSTGRES_DB=queueless

# Service Databases & Credentials
NOTIFICATION_DB_USER=notification_user
NOTIFICATION_DB_PASSWORD=${notificationDbPassword}
NOTIFICATION_DB_NAME=notification_db

QUEUE_DB_USER=queue_user
QUEUE_DB_PASSWORD=${queueDbPassword}
QUEUE_DB_NAME=queue_db

# Redis Configuration
REDIS_HOST=redis
REDIS_PORT=6379

# RabbitMQ Configuration
RABBITMQ_DEFAULT_USER=guest
RABBITMQ_DEFAULT_PASS=guest

# Security Secrets & Tokens (Required)
INTERNAL_TOKEN=${internalToken}
JWT_ACCESS_SECRET=${jwtAccessSecret}
JWT_ACCESS_EXPIRES_IN=15m
JWT_REFRESH_SECRET=${jwtRefreshSecret}
JWT_REFRESH_EXPIRES_IN=7d

# SMTP & Mail Configuration
SMTP_HOST=mailhog
SMTP_PORT=1025
SMTP_USER=
SMTP_PASS=
EMAIL_FROM="QueueLess Alerts <no-reply@queueless.local>"

# Business & Queue Domain Rules
BUSINESS_TIMEZONE=Asia/Kolkata
NOTIFICATIONS_ENABLED=true
QUEUE_NOTIFY_POSITION=3
DEFAULT_SERVICE_MINUTES=10
CHECKIN_EARLY_MINUTES=30
CHECKIN_GRACE_MINUTES=15
CANCELLATION_CUTOFF_MINUTES=60
REMINDER_MINUTES_BEFORE=60

# Grafana Monitoring (Phase 11C)
GRAFANA_ADMIN_USER=admin
GRAFANA_ADMIN_PASSWORD=${grafanaAdminPassword}
`;

  fs.writeFileSync(envPath, envContent, 'utf-8');
  console.log('✅ Generated new .env file with cryptographically secure random secrets:');
  console.log(`   - POSTGRES_PASSWORD: [${postgresPassword.length} chars]`);
  console.log(`   - NOTIFICATION_DB_PASSWORD: [${notificationDbPassword.length} chars]`);
  console.log(`   - QUEUE_DB_PASSWORD: [${queueDbPassword.length} chars]`);
  console.log(`   - INTERNAL_TOKEN: [${internalToken.length} chars]`);
  console.log(`   - JWT_ACCESS_SECRET: [${jwtAccessSecret.length} chars]`);
  console.log(`   - JWT_REFRESH_SECRET: [${jwtRefreshSecret.length} chars]`);
  console.log(`   - GRAFANA_ADMIN_PASSWORD: [${grafanaAdminPassword.length} chars]`);
}

generateEnv();
